"""
pipeline/nodes/pr_author.py — Stage 8: PR Author Agent

Writes a structured PR description via LLM, opens the pull request on GitHub,
posts inline review comments for each finding in review_findings, and links
the original issue to the new PR.

DRY_RUN=true (env var) skips all GitHub API calls and returns a synthetic
pr dict — use this during development to avoid creating real GitHub objects.

Required env vars:
    GITHUB_TOKEN  — Personal access token with repo scope.
    GITHUB_REPO   — Target repo in "owner/repo" format.
    DRY_RUN       — Set to "true" to skip GitHub API calls (default: false).
"""

import logging
import os
from typing import Optional

import httpx
from dotenv import load_dotenv
from pydantic import BaseModel, Field

from pipeline.models import flash_model
from pipeline.state import FindingItem, PipelineState

load_dotenv()

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

PR_AUTHOR_SYSTEM_PROMPT = """\
You are a senior software engineer writing a GitHub pull request description.
Your PR description must be clear, informative, and professional.

You will be given:
- A requirements summary (what was requested)
- A list of changed files with their explanations
- Test results
- Review findings

Produce a valid JSON object with exactly these fields:
- "title": short PR title (max 72 chars, imperative mood, no period)
- "summary": 1-2 sentence overview of what this PR does
- "motivation": why this change is needed (1 paragraph, references the issue)
- "changes_made": bullet-point list of changes (one string per file changed)
- "test_plan": describe what was tested and the outcome
- "risk_assessment": brief paragraph on risk level and what reviewers should focus on

Respond with a valid JSON object that strictly follows the provided schema.
Do not include markdown fences. Use exactly the field names listed above.
"""


# ---------------------------------------------------------------------------
# Pydantic model for LLM-generated PR description
# ---------------------------------------------------------------------------

class PRDescription(BaseModel):
    """Structured PR description generated by the LLM."""

    title: str = Field(
        description=(
            "Short PR title. Imperative mood, max 72 characters, no period. "
            "Example: 'Add input validation to UserModel'. "
            "Field name: title"
        )
    )
    summary: str = Field(
        description=(
            "One to two sentence overview of what this PR does. "
            "Field name: summary"
        )
    )
    motivation: str = Field(
        description=(
            "One paragraph explaining why this change is needed. "
            "Reference the issue number if available. "
            "Field name: motivation"
        )
    )
    changes_made: list[str] = Field(
        description=(
            "List of changes made, one entry per file. Each entry is a "
            "bullet-point string like 'models/user.py: Added email validation'. "
            "Field name: changes_made"
        )
    )
    test_plan: str = Field(
        description=(
            "Describe what was tested and whether all tests passed. "
            "Include counts of new tests generated. "
            "Field name: test_plan"
        )
    )
    risk_assessment: str = Field(
        description=(
            "Brief paragraph on risk level (low/medium/high) and what "
            "reviewers should focus on. "
            "Field name: risk_assessment"
        )
    )


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _build_pr_body(desc: PRDescription, findings_count: int) -> str:
    """
    Render PRDescription + finding counts into a GitHub-flavoured markdown
    body string. This is what appears in the PR description on GitHub.
    """
    changes_list = "\n".join(f"- {c}" for c in desc.changes_made)
    body = f"""## Summary
{desc.summary}

## Motivation
{desc.motivation}

## Changes Made
{changes_list}

## Test Plan
{desc.test_plan}

## Risk Assessment
{desc.risk_assessment}

---
*This PR was opened automatically by the SDLC pipeline. "
{findings_count} review finding(s) have been posted as inline comments.*
"""
    return body


def _post_github(
    method: str,
    path: str,
    token: str,
    payload: Optional[dict] = None,
) -> dict:
    """
    Make a GitHub API call. Raises on HTTP errors so the caller can catch.

    Args:
        method: HTTP method string ("POST", "PATCH", etc.)
        path:   GitHub API path starting with "/", e.g. "/repos/owner/repo/pulls"
        token:  GitHub personal access token.
        payload: JSON body dict (optional).

    Returns:
        Parsed JSON response as a dict.
    """
    url = f"https://api.github.com{path}"
    headers = {
        "Authorization": f"Bearer {token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    with httpx.Client(timeout=30) as client:
        response = client.request(method, url, headers=headers, json=payload)
        response.raise_for_status()
        return response.json()


# ---------------------------------------------------------------------------
# Node function
# ---------------------------------------------------------------------------

def pr_author_node(state: PipelineState) -> dict:
    """
    Stage 8 — PR Author Agent.

    Reads:
        state["issue"]             — original GitHub issue (number, title, body).
        state["requirements_spec"] — used to write the PR motivation section.
        state["code_changes"]      — list of CodeChange objects; file paths and
                                     explanations are included in the description.
        state["test_results"]      — included in the PR's test plan section.
        state["review_findings"]   — each FindingItem is posted as an inline
                                     review comment.

    Does:
        1. Calls the LLM to produce a structured PRDescription.
        2. If DRY_RUN=false: opens the GitHub PR via REST API.
        3. If DRY_RUN=false: posts one inline comment per review finding.
        4. If DRY_RUN=false: posts a comment on the original issue linking to the PR.

    Writes:
        state["pr"]              — GitHub PR payload (or synthetic dict in DRY_RUN).
        state["pipeline_status"] — "pr_opened" | "pr_dry_run" | "pr_failed"
    """
    dry_run = os.getenv("DRY_RUN", "false").lower() == "true"
    github_token = os.getenv("GITHUB_TOKEN", "")
    github_repo = os.getenv("GITHUB_REPO", "")  # "owner/repo"

    issue = state.get("issue", {})
    requirements_spec = state.get("requirements_spec")
    code_changes = state.get("code_changes", [])
    test_results = state.get("test_results")
    review_findings = state.get("review_findings")

    # ------------------------------------------------------------------
    # Step 1: Generate PR description via LLM
    # ------------------------------------------------------------------
    changes_text = "\n".join(
        f"- {c.file_path}: {c.explanation}" for c in code_changes
    ) or "No code changes recorded."

    test_summary = "No test results available."
    if test_results:
        test_summary = (
            f"Status: {test_results.final_status}. "
            f"Existing tests passed: {test_results.existing_tests_passed}. "
            f"New tests: {test_results.new_tests_generated} generated, "
            f"{test_results.new_tests_passed} passed, "
            f"{test_results.new_tests_failed} failed."
        )

    all_findings: list[FindingItem] = []
    findings_summary = "No review findings."
    if review_findings:
        all_findings = (
            review_findings.blocking_issues
            + review_findings.major_issues
            + review_findings.minor_issues
            + review_findings.suggestions
        )
        findings_summary = (
            f"Recommendation: {review_findings.recommendation}. "
            f"Blocking: {len(review_findings.blocking_issues)}, "
            f"Major: {len(review_findings.major_issues)}, "
            f"Minor: {len(review_findings.minor_issues)}, "
            f"Suggestions: {len(review_findings.suggestions)}."
        )

    user_prompt = f"""Issue: #{issue.get('number', 'N/A')} — {issue.get('title', 'No title')}

Requirements summary:
{requirements_spec.summary if requirements_spec else 'Not available.'}

Files changed:
{changes_text}

Test results:
{test_summary}

Review findings:
{findings_summary}

Write the PR description now."""

    desc: Optional[PRDescription] = None
    try:
        structured = flash_model.with_structured_output(
            PRDescription, method="json_mode"
        )
        desc = structured.invoke([
            {"role": "system", "content": PR_AUTHOR_SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt},
        ])
        logger.info(
            "PR description generated",
            extra={"title": desc.title, "files_changed": len(code_changes)},
        )
    except Exception as exc:
        logger.error(
            "LLM call failed in pr_author_node; falling back to template description",
            extra={"error": str(exc)},
        )

    # Fallback description if LLM fails
    if desc is None:
        desc = PRDescription(
            title=f"Fix: {issue.get('title', 'automated change')[:60]}",
            summary="Automated PR generated by SDLC pipeline.",
            motivation=f"Resolves issue #{issue.get('number', 'N/A')}.",
            changes_made=[c.file_path for c in code_changes] or ["No changes"],
            test_plan=test_summary,
            risk_assessment="Risk assessment unavailable — LLM call failed.",
        )

    pr_body = _build_pr_body(desc, len(all_findings))

    # ------------------------------------------------------------------
    # Step 2: DRY_RUN guard — skip all GitHub API calls if set
    # ------------------------------------------------------------------
    if dry_run:
        logger.info("DRY_RUN=true — skipping GitHub API calls")
        synthetic_pr = {
            "number": 0,
            "html_url": "https://github.com/dry-run/pr/0",
            "title": desc.title,
            "body": pr_body,
            "state": "open",
            "dry_run": True,
        }
        return {
            "pr": synthetic_pr,
            "pipeline_status": "pr_dry_run",
        }

    # ------------------------------------------------------------------
    # Step 3: Validate GitHub config before making any API calls
    # ------------------------------------------------------------------
    if not github_token or not github_repo:
        logger.error(
            "GITHUB_TOKEN or GITHUB_REPO not set; cannot open PR",
            extra={"has_token": bool(github_token), "repo": github_repo},
        )
        return {
            "pr": {"error": "missing_github_config"},
            "pipeline_status": "pr_failed",
        }

    # ------------------------------------------------------------------
    # Step 4: Open the pull request
    # ------------------------------------------------------------------
    pr_payload: dict = {}
    pr_number: Optional[int] = None

    try:
        issue_number = issue.get("number")
        # Read branches from env — HEAD_BRANCH is the branch the pipeline
        # commits to; BASE_BRANCH is the merge target. Both are set in .env.
        # Previously this derived head_branch from the issue number
        # (sdlc/issue-{N}), but that branch never exists. HEAD_BRANCH does.
        head_branch = os.getenv("HEAD_BRANCH", "sdlc/automated")
        base_branch = os.getenv("BASE_BRANCH", "main")

        pr_payload = _post_github(
            "POST",
            f"/repos/{github_repo}/pulls",
            github_token,
            {
                "title": desc.title,
                "body": pr_body,
                "head": head_branch,
                "base": base_branch,
            },
        )
        pr_number = pr_payload.get("number")
        logger.info(
            "Pull request opened",
            extra={"pr_number": pr_number, "url": pr_payload.get("html_url")},
        )
    except Exception as exc:
        _gh_body = ""
        _gh_resp = getattr(exc, "response", None)
        if _gh_resp is not None:
            try: _gh_body = f" | HTTP {_gh_resp.status_code}: {_gh_resp.text[:400]}"
            except Exception: pass
        logger.error(
            "Failed to open GitHub PR",
            extra={
                "exc_type": type(exc).__name__,
                "error":    str(exc)[:300] + _gh_body,
                "repo":     github_repo,
            },
        )
        return {
            "pr": {"error": str(exc)},
            "pipeline_status": "pr_failed",
        }

    # ------------------------------------------------------------------
    # Step 5: Post inline review comments for each finding
    # ------------------------------------------------------------------
    if pr_number and all_findings:
        for finding in all_findings:
            severity_tag = finding.severity.upper()
            comment_body = (
                f"**[{severity_tag}] {finding.title}**\n\n"
                f"{finding.description}\n\n"
                f"**Suggestion:** {finding.suggestion}"
            )
            try:
                # GitHub inline PR review comments require a commit SHA and
                # diff position; we use the simpler issue-comment endpoint
                # which posts to the PR's conversation thread instead.
                # ponytail: true inline diff comments need commit_id + position
                # from the GitHub Commits API. Upgrade path: fetch the head
                # commit SHA after PR creation and use /pulls/{pr}/comments.
                _post_github(
                    "POST",
                    f"/repos/{github_repo}/issues/{pr_number}/comments",
                    github_token,
                    {"body": comment_body},
                )
            except Exception as exc:
                # Non-fatal: log and continue posting remaining comments.
                logger.warning(
                    "Failed to post review comment",
                    extra={
                        "finding_title": finding.title,
                        "error": str(exc),
                    },
                )

    # ------------------------------------------------------------------
    # Step 6: Link the original issue to the new PR via a comment
    # ------------------------------------------------------------------
    issue_number = issue.get("number")
    if issue_number and pr_number:
        pr_url = pr_payload.get("html_url", "")
        try:
            _post_github(
                "POST",
                f"/repos/{github_repo}/issues/{issue_number}/comments",
                github_token,
                {"body": f"Pull request opened: {pr_url}"},
            )
        except Exception as exc:
            # Non-fatal: the PR was already created; issue linking is cosmetic.
            logger.warning(
                "Failed to post issue link comment",
                extra={"issue_number": issue_number, "error": str(exc)},
            )

    return {
        "pr": pr_payload,
        "pipeline_status": "pr_opened",
    }
